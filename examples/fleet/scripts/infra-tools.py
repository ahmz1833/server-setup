#!/usr/bin/env python3
"""Makefile helpers: vault masking, credential check, ~/.ssh/config block.

Source of truth: ahmz1833/server-setup examples/starter/scripts/ (copies are synced).
Unknown key names count as credentials so new secrets stay hidden by default.
"""
import argparse
import datetime
import json
import os
import re
import sys

IDENTIFIER_RE = re.compile(
    r"(^|_)(ip|ips|ipv4|ipv6|addr|address|addresses|host|hostname|hosts|fqdn|domain|domains|"
    r"port|ports|ssh_port|cidr|cidrs|subnet|subnets|net|nets|gateway|iface|interface|mac|asn|"
    r"user|username|admin_user|login|email|region|location|provider|dc)$",
    re.IGNORECASE,
)
CREDENTIAL_HINT_RE = re.compile(
    r"pass|secret|token|key|seed|uuid|cert|private|cookie|salt|hash|dsn|auth|base_path|otp|"
    r"credential",
    re.IGNORECASE,
)
HIDDEN = "<hidden credential>"


def is_identifier(name: str) -> bool:
    name = str(name)
    if CREDENTIAL_HINT_RE.search(name):
        return False
    return bool(IDENTIFIER_RE.search(name))


def is_credential_var(name: str) -> bool:
    if CREDENTIAL_HINT_RE.search(name):
        return True
    if name.startswith("vault_"):
        return not is_identifier(name[len("vault_"):]) and not is_identifier(name)
    return False


def mask_value(key, value, parent_identifier=False):
    if isinstance(value, dict):
        return {k: mask_value(k, v, False) for k, v in value.items()}
    if isinstance(value, list):
        return [mask_value(key, v, is_identifier(key)) for v in value]
    if is_identifier(key) or parent_identifier:
        return value
    return HIDDEN


def cmd_mask(_args):
    import yaml

    data = yaml.safe_load(sys.stdin) or {}
    out = {}
    for k, v in data.items():
        if k.startswith("vault_"):
            out[k] = mask_value(k[len("vault_"):], v)
        elif CREDENTIAL_HINT_RE.search(k) and isinstance(v, str) and "{{" not in v:
            out[k] = HIDDEN
        else:
            out[k] = v
    yaml.safe_dump(out, sys.stdout, default_flow_style=False, sort_keys=True, allow_unicode=True)


def cmd_is_credential(args):
    sys.exit(0 if is_credential_var(args.name) else 1)


def parse_hosts(raw: str) -> dict:
    start = raw.find("{")
    doc = json.loads(raw[start:])
    hosts = {}
    for play in doc.get("plays", []):
        for task in play.get("tasks", []):
            for host, res in task.get("hosts", {}).items():
                msg = res.get("msg")
                if isinstance(msg, str):
                    try:
                        msg = json.loads(msg)
                    except ValueError:
                        continue
                if isinstance(msg, dict):
                    hosts[host] = msg
    return hosts


def render_block(project: str, hosts: dict) -> str:
    lines = [f"# >>> {project} (generated by `make ssh-config` — edit the inventory/vault, not this block) >>>"]
    for name in sorted(hosts):
        h = hosts[name]
        if h.get("skip"):
            continue
        lines.append(f"Host {name}")
        lines.append(f"    HostName {h.get('host') or name}")
        if str(h.get("port") or "22") != "22":
            lines.append(f"    Port {h['port']}")
        if h.get("user"):
            lines.append(f"    User {h['user']}")
        if h.get("key"):
            lines.append(f"    IdentityFile {h['key']}")
            lines.append("    IdentitiesOnly yes")
        for k, v in sorted((h.get("extra") or {}).items()):
            lines.append(f"    {k} {v}")
        lines.append("")
    lines.append(f"# <<< {project} <<<")
    return "\n".join(lines) + "\n"


STANZA_RE = re.compile(r"^\s*(Host|Match)\s+(.*)$", re.IGNORECASE)


def remove_block(text: str, project: str) -> str:
    pat = re.compile(
        r"^# >>> " + re.escape(project) + r" .*?^# <<< " + re.escape(project) + r" <<<\n?",
        re.MULTILINE | re.DOTALL,
    )
    return pat.sub("", text)


def find_conflicts(text: str, names: set):
    lines = text.splitlines(keepends=True)
    out, i = [], 0
    while i < len(lines):
        m = STANZA_RE.match(lines[i])
        if m and m.group(1).lower() == "host":
            pats = m.group(2).split()
            j = i + 1
            while j < len(lines) and not STANZA_RE.match(lines[j]):
                j += 1
            if len(pats) == 1 and pats[0] in names:
                out.append((i, j, pats[0]))
            i = j
        else:
            i += 1
    return out, lines


def cmd_ssh_config(args):
    hosts = parse_hosts(sys.stdin.read())
    if not hosts:
        sys.exit("ssh-config: no hosts resolved (inventory/vault problem?)")
    path = os.path.expanduser(args.file)
    text = open(path).read() if os.path.exists(path) else ""
    text = remove_block(text, args.project)
    conflicts, lines = find_conflicts(text, set(hosts))
    if conflicts:
        names = ", ".join(c[2] for c in conflicts)
        if not args.replace:
            print(f"ssh-config: existing hand-written entries for: {names}")
            print("            they would shadow or duplicate the managed block; re-run with REPLACE=1 to "
                  "remove them (a backup is written first)")
            sys.exit(1)
        drop = set()
        for s, e, _ in conflicts:
            drop.update(range(s, e))
        text = "".join(l for n, l in enumerate(lines) if n not in drop)
    block = render_block(args.project, hosts)
    # Include must stay first; the block goes next because ssh uses the first matching value.
    head, rest = [], text.splitlines(keepends=True)
    while rest and re.match(r"^\s*(Include\b|#|$)", rest[0]) and not rest[0].startswith("# >>>"):
        if rest[0].strip().lower().startswith("include") or rest[0].strip() == "" and head:
            head.append(rest.pop(0))
        else:
            break
    new = "".join(head) + block + ("\n" if rest and rest[0].strip() else "") + "".join(rest)
    current = open(path).read() if os.path.exists(path) else ""
    if args.check:
        sys.exit(0 if current == new else 1)
    if current == new:
        print(f"ssh-config: {args.file} already up to date")
        return
    if os.path.exists(path):
        backup = f"{path}.bak-{datetime.datetime.now():%Y%m%d-%H%M%S}"
        with open(backup, "w") as f:
            f.write(open(path).read())
        os.chmod(backup, 0o600)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(new)
    os.chmod(path, 0o600)
    managed = [n for n in sorted(hosts) if not hosts[n].get("skip")]
    print(f"ssh-config: {len(managed)} host(s) written to {args.file}: {' '.join(managed)}")
    if conflicts:
        print(f"ssh-config: replaced hand-written entries: {', '.join(c[2] for c in conflicts)} (backup kept)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("mask")
    p = sub.add_parser("is-credential")
    p.add_argument("name")
    p = sub.add_parser("ssh-config")
    p.add_argument("--project", required=True)
    p.add_argument("--file", default="~/.ssh/config")
    p.add_argument("--replace", action="store_true")
    p.add_argument("--check", action="store_true", help="exit 1 if the file would change")
    args = ap.parse_args()
    {"mask": cmd_mask, "is-credential": cmd_is_credential, "ssh-config": cmd_ssh_config}[args.cmd](args)


if __name__ == "__main__":
    main()
