#!/usr/bin/env python3
"""Generate docs/roles-index.md from roles/*/meta/argument_specs.yml.

The argument specs are the single source of truth for role variables; this index is a
compact, greppable view of them for humans and AI agents. Do not edit the output by hand.

Usage: scripts/gen-roles-index.py [--check]
  --check  exit 1 if docs/roles-index.md is out of date (CI)
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "roles-index.md"
FQCN = "ahmz1833.server_setup"


def ansible_markup(text: str) -> str:
    """Convert ansible-doc markup (C(), I(), B(), V(), O(), M()) to markdown."""
    text = re.sub(r"[CVO]\(([^()]*)\)", r"`\1`", text)
    text = re.sub(r"[IB]\(([^()]*)\)", r"*\1*", text)
    text = re.sub(r"M\(([^()]*)\)", r"`\1`", text)
    return text


def as_text(desc) -> str:
    if desc is None:
        return ""
    if isinstance(desc, list):
        desc = " ".join(str(d) for d in desc)
    return ansible_markup(" ".join(str(desc).split()))


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def fmt_default(opt: dict) -> str:
    if "default" not in opt:
        return ""
    val = opt["default"]
    if isinstance(val, str):
        s = json.dumps(val, ensure_ascii=False)
    else:
        s = json.dumps(val, ensure_ascii=False, separators=(", ", ": "))
    if len(s) > 48:
        s = s[:45] + "…"
    return f"`{cell(s)}`"


def fmt_type(opt: dict) -> str:
    t = opt.get("type", "str")
    if t == "list" and opt.get("elements"):
        t = f"list[{opt['elements']}]"
    if opt.get("required"):
        t += " **req**"
    return t


def rows(options: dict, prefix: str = ""):
    for name in sorted(options):
        opt = options[name] or {}
        desc = as_text(opt.get("description"))
        if opt.get("choices"):
            desc += " Choices: " + ", ".join(f"`{c}`" for c in opt["choices"]) + "."
        yield f"| `{prefix}{name}` | {fmt_type(opt)} | {fmt_default(opt)} | {cell(desc)} |"
        sub = opt.get("options")
        if sub:
            yield from rows(sub, prefix=f"{prefix}{name}[]." if opt.get("type") == "list" else f"{prefix}{name}.")


def render() -> str:
    out = [
        "# Roles index",
        "",
        "<!-- GENERATED by scripts/gen-roles-index.py from roles/*/meta/argument_specs.yml — do not edit -->",
        "",
        f"Every user-settable variable of `{FQCN}`, generated from the roles' argument specs.",
        "Same data, rendered: `ansible-doc -t role " + FQCN + ".<role>`. Behaviour details: each role's README.",
        "",
        "Conventions: *req* = required. `raw` = any type (often templated or derived). An empty default",
        "means it is derived from other variables/facts (see description) or is a large structure in",
        "`roles/<role>/defaults/main.yml`. `x[].y` = key `y` of each item in list `x`.",
        "",
    ]
    roles = sorted(p.parent.parent.name for p in ROOT.glob("roles/*/meta/argument_specs.yml"))
    out.append("Roles: " + " · ".join(f"[{r}](#{r})" for r in roles))
    out.append("")
    for role in roles:
        spec = yaml.safe_load((ROOT / "roles" / role / "meta" / "argument_specs.yml").read_text())
        eps = spec.get("argument_specs", {})
        out.append(f"## {role}")
        out.append("")
        for ep_name, ep in eps.items():
            if ep_name != "main":
                out.append(f"### Entry point `{ep_name}` (`tasks_from: {ep_name}`)")
                out.append("")
            out.append(f"**{as_text(ep.get('short_description'))}**")
            out.append("")
            for para in ep.get("description") or []:
                out.append(f"- {as_text(para)}")
            out.append("")
            opts = ep.get("options") or {}
            if ep_name != "main" and opts:
                out.append("Options: " + ", ".join(f"`{o}`" for o in sorted(opts)) + " (see main).")
                out.append("")
                continue
            out.append("| Variable | Type | Default | Description |")
            out.append("|---|---|---|---|")
            out.extend(rows(opts))
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/gen-roles-index.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
